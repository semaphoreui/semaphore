"""Z16 Key Store — keys and secret storages in Seed Demo that the base set lacks:

- «Z16 Generated SSH» — ssh, generated by the server: the edit dialog shows the «Public key:» block
  (the key pair is random, the public key is masked in the shots);
- «Z16 Empty SSH» — ssh without a private key: the server lists it with `empty: true` (the red
  «Empty» chip); no references, so its delete button opens the confirmation;
- «Z16 Env» — login_password read from the environment variable Z16_SECRET;
- «Z16 File» — ssh read from the file /etc/semaphore/z16.key;
- storages «Z16 Vault» (writable) and «Z16 Vault RO» (read-only), HashiCorp Vault at an unreachable
  address with a fake token, never synced — the Storage menu of the key form;
- «Z16 Vault RO» key — ssh read from the read-only storage at secret/z16 (a key on a writable Vault
  would need a live Vault to store the secret).

Idempotent: an existing key or storage (same name) is kept. No global switches: secret storages
need the Enterprise plan the fixture already has (an OSS build or a smaller plan skips them).
"""

DEMO = "Seed Demo"
VAULT, VAULT_RO = "Z16 Vault", "Z16 Vault RO"
VAULT_PARAMS = {"url": "http://127.0.0.1:9/", "mount": "secret"}


def _key(pid, name, typ, **extra):
    body = {"name": name, "type": typ, "project_id": pid, "ssh": {}, "login_password": {}}
    body.update(extra)
    return body


def seed(ctx):
    pid = ctx.project_id(DEMO)
    keys = f"/project/{pid}/keys"

    ctx.ensure(keys, _key(pid, "Z16 Generated SSH", "ssh", generate_ssh_key=True, ssh={"login": "git"}),
               kind="key")
    ctx.ensure(keys, _key(pid, "Z16 Empty SSH", "ssh", ssh={"login": "", "passphrase": "", "private_key": ""}),
               kind="key")
    ctx.ensure(keys, _key(pid, "Z16 Env", "login_password", source_storage_type="env",
                          source_storage_key="Z16_SECRET"), kind="key")
    ctx.ensure(keys, _key(pid, "Z16 File", "ssh", source_storage_type="file",
                          source_storage_key="/etc/semaphore/z16.key"), kind="key")

    storages = f"/project/{pid}/secret_storages"
    ids = {}
    for name, readonly in ((VAULT, False), (VAULT_RO, True)):
        st = ctx.optional("storage", name, lambda: ctx.ensure(storages, {
            "name": name, "type": "vault", "params": VAULT_PARAMS, "project_id": pid, "readonly": readonly,
            "secret": "z16-not-a-real-token", "sync_enabled": False, "sync_interval": 0,
        }, kind="storage"))
        if st:
            ids[name] = st["id"]
    if VAULT_RO not in ids:  # no secret storages in this build / plan
        return
    ctx.ensure(keys, _key(pid, "Z16 Vault RO", "ssh", source_storage_type="vault",
                          source_storage_id=ids[VAULT_RO], source_storage_key="secret/z16"), kind="key")
